    with pytest.raises(GeoAIUnitError) as exc:
        tool_registry.invoke_tool(tool, args)
    assert "Unit dimension mismatch" in str(exc.value)
    assert exc.value.errors[0]["field"] == bad and exc.value.errors[0]["type"] == "unit_dimension_mismatch"


