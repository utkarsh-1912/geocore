"""
Strict tool schemas & deterministic unit normalisation (AGENTS.md §5, §7, §16, §17, §25).

- Unknown keys are rejected with a structured, recoverable error.
- Documented aliases are still accepted.
- Unit strings are converted by core.geoai.units for auto-registered Groundhog tools.
- Every tool's input fields match the parameters of the callable it invokes.
- Results for correct inputs equal direct Groundhog calls (deterministic oracle).
"""
import importlib
import inspect
import math

import pytest

from core.registry import registry  # noqa: F401  (populates auto-registered Groundhog tools)
import core.geoai.tool_definitions  # noqa: F401  (registers curated tools)
from core.geoai.exceptions import GeoAIUnitError, GeoAIValidationError
from core.geoai.schemas.shallowfoundations import ShallowFoundationCapacityUndrainedInput
from core.geoai.tool_registry import tool_registry
from core.geoai.units import convert_unit, normalize_parameter_value
from core.geoai.validator import validate_and_coerce_inputs


def _invoke(tool, **args):
    res = tool_registry.invoke_tool(tool, args)
    res.pop("_provenance", None)
    return res


def _groundhog(tool_name):
    """Resolve the real Groundhog function behind a tool (independent of the registry)."""
    target = tool_registry.get_tool(tool_name).target_callable()
    resolved = target.resolve() if hasattr(target, "resolve") else target
    return getattr(importlib.import_module(resolved.__module__), resolved.__name__)


def _assert_same_result(actual, expected):
    assert set(expected) <= set(actual)
    for k, v in expected.items():
        if isinstance(v, float) and math.isnan(v):
            assert math.isnan(actual[k])
        elif isinstance(v, (int, float)) and not isinstance(v, bool):
            assert actual[k] == pytest.approx(v, rel=1e-12), k
        else:
            assert actual[k] == v, k


def _auto(tool_name):
    tool = tool_registry.get_tool(tool_name)
    assert tool is not None and getattr(tool.input_model, "geoai_autogenerated", False)
    return tool


# ---------------------------------------------------------------- unknown keys
def test_unknown_key_rejected_on_auto_tool_with_valid_names():
    _auto("nq_frictionangle_sand")
    with pytest.raises(GeoAIValidationError) as exc:
        tool_registry.invoke_tool("nq_frictionangle_sand", {"friction_angle": 32, "bogus": 3})
    err = exc.value
    assert "unknown parameter(s) 'bogus'" in err.message
    assert "Valid parameters: friction_angle" in err.message
    detail = next(d for d in err.errors if d["type"] == "unknown_parameter")
    assert detail["field"] == "bogus" and detail["valid_parameters"] == ["friction_angle"]
    assert err.to_dict()["status"] == "ValidationError"


def test_misspelled_key_gets_suggestion_and_missing_field_reported():
    with pytest.raises(GeoAIValidationError) as exc:
        tool_registry.invoke_tool("nq_frictionangle_sand", {"friction_angl": 32})
    err = exc.value
    assert "did you mean 'friction_angle'" in err.message
    types = {d["type"] for d in err.errors}
    assert {"unknown_parameter", "missing"} <= types


def test_unknown_key_rejected_on_curated_tool():
    with pytest.raises(GeoAIValidationError, match="unknown parameter"):
        tool_registry.invoke_tool("calculate_relative_density",
                                  {"void_ratio": 0.6, "e_min": 0.4, "e_max": 0.9, "density": 1})


def test_curated_aliases_still_accepted():
    ref = _invoke("calculate_relative_density", void_ratio=0.6, e_min=0.4, e_max=0.9)
    for key in ("voidratio", "e"):
        assert _invoke("calculate_relative_density", **{key: 0.6, "emin": 0.4, "emax": 0.9}) == ref


def test_auto_alias_from_docstring_name_case():
    # Groundhog documents ':param PI:' for the signature parameter 'pi'.
    args = dict(strain=0.01, sigma_m_eff=100.0)
    assert _invoke("modulusreduction_plasticity_ishibashi", PI=20.0, **args) == \
        _invoke("modulusreduction_plasticity_ishibashi", pi=20.0, **args)


def test_json_schema_offered_to_model_is_strict_with_clean_units():
    schema = next(t for t in tool_registry.list_tools() if t["name"] == "nq_frictionangle_sand")["input_schema"]
    assert schema["additionalProperties"] is False
    prop = schema["properties"]["friction_angle"]
    assert prop["unit"] == "deg" and prop["type"] == "number"


def test_ui_path_keeps_legacy_passthrough_for_auto_schemas():
    # core.registry special cases read extra keys (e.g. 'nan_strategy'); the UI path keeps them.
    validated, _ = validate_and_coerce_inputs("nq_frictionangle_sand", {"friction_angle": "32", "ui_hint": "x"})
    assert validated["friction_angle"] == 32.0 and validated["ui_hint"] == "x"
    with pytest.raises(GeoAIValidationError, match="unknown parameter"):
        validate_and_coerce_inputs("calculate_relative_density", {"void_ratio": 0.6, "e_min": 0.4,
                                                                  "e_max": 0.9, "bogus": 1})


# ---------------------------------------------------------------- unit conversion (auto tools)
def test_angle_radians_converted_to_degrees():
    rad = math.radians(32.0)
    assert _invoke("nq_frictionangle_sand", friction_angle=f"{rad} rad") == \
        pytest.approx(_invoke("nq_frictionangle_sand", friction_angle=32.0))
    assert _invoke("nq_frictionangle_sand", friction_angle="32°") == _invoke("nq_frictionangle_sand", friction_angle=32.0)


def test_pressure_converted_to_kpa():
    direct = _groundhog("overburdencorrection_spt_liaowhitman")(N=20, sigma_vo_eff=150.0)
    res = _invoke("overburdencorrection_spt_liaowhitman", N=20, sigma_vo_eff="0.15 MPa")
    _assert_same_result(res, direct)
    res_psf = _invoke("overburdencorrection_spt_liaowhitman", N=20, sigma_vo_eff="3000 psf")
    kpa = convert_unit(3000, "psf", "kPa")
    _assert_same_result(res_psf, _groundhog("overburdencorrection_spt_liaowhitman")(N=20, sigma_vo_eff=kpa))


def test_unit_weight_converted_to_kn_per_m3():
    kn = convert_unit(120.0, "pcf", "kN/m3")
    direct = _groundhog("dryunitweight_watercontent")(watercontent=0.2, bulkunitweight=kn)
    _assert_same_result(_invoke("dryunitweight_watercontent", watercontent=0.2, bulkunitweight="120 pcf"), direct)
    _assert_same_result(_invoke("dryunitweight_watercontent", watercontent=0.2, bulkunitweight=f"{kn} kN/m³"), direct)


def test_length_converted_to_metres():
    direct = _groundhog("stresses_stripload")(z=5.0, x=0.5, width=2.0, imposedstress=100.0)
    res = _invoke("stresses_stripload", z="5000 mm", x="50 cm", width="2 m", imposedstress="0.1 MPa")
    _assert_same_result(res, direct)


