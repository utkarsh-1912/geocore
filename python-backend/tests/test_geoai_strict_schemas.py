# ---------------------------------------------------------------- percent / fraction rule
def test_percent_to_fraction_for_dimensionless_field():
    direct = _groundhog("dryunitweight_watercontent")(watercontent=0.25, bulkunitweight=19.0)
    _assert_same_result(_invoke("dryunitweight_watercontent", watercontent="25 %", bulkunitweight=19.0), direct)
    _assert_same_result(_invoke("dryunitweight_watercontent", watercontent=0.25, bulkunitweight=19.0), direct)


def test_percent_field_accepts_fraction_with_unit_and_bare_percent():
    # 'strain' is documented in pct; bare numbers are taken as percent (never guessed).
    base = dict(pi=20.0, sigma_m_eff=100.0)
    ref = _invoke("modulusreduction_plasticity_ishibashi", strain=0.1, **base)
    assert _invoke("modulusreduction_plasticity_ishibashi", strain="0.1 %", **base) == ref
    assert _invoke("modulusreduction_plasticity_ishibashi", strain="0.001 fraction", **base) == pytest.approx(ref)


def test_units_percent_rules():
    assert normalize_parameter_value("25 %", expected_unit="-") == pytest.approx(0.25)
    assert normalize_parameter_value("0.25 ratio", expected_unit="-") == pytest.approx(0.25)
    assert normalize_parameter_value(0.25, expected_unit="-") == 0.25
    assert normalize_parameter_value("25 %", expected_unit="pct") == pytest.approx(25.0)
    assert normalize_parameter_value("0.25 fraction", expected_unit="%") == pytest.approx(25.0)
    assert normalize_parameter_value(0.25, expected_unit="pct") == 0.25
    assert convert_unit(0.5, "ratio", "-") == pytest.approx(0.5)
    assert convert_unit(0.5, "-", "ratio") == pytest.approx(0.5)
    with pytest.raises(GeoAIUnitError):
        normalize_parameter_value("5 blows", expected_unit="-", field_name="N")


def test_units_outside_taxonomy_accept_only_identical_unit():
    assert normalize_parameter_value("2 kPa/m", expected_unit="kPa/m") == 2.0
    assert normalize_parameter_value(2, expected_unit="kPa/m") == 2
    with pytest.raises(GeoAIUnitError, match="cannot be converted automatically"):
        normalize_parameter_value("2 MPa/m", expected_unit="kPa/m", field_name="su_increase")
    inst = ShallowFoundationCapacityUndrainedInput(width=2.0, unit_weight="18 kN/m3", su_base="0.05 MPa",
                                                   su_increase="1.5 kPa/m")
    assert (inst.su_base, inst.su_increase) == (pytest.approx(50.0), 1.5)


def test_units_strip_sphinx_markup_and_superscripts():
    assert normalize_parameter_value("1.5 MPa", expected_unit=":math:`kPa`") == pytest.approx(1500.0)
    assert normalize_parameter_value("18 kN/m³", expected_unit="kN/m3") == pytest.approx(18.0)


# ---------------------------------------------------------------- signature match (all tools)
def _named_params(sig):
    return {n: p for n, p in sig.parameters.items()
            if p.kind not in (p.VAR_KEYWORD, p.VAR_POSITIONAL) and n not in ("self", "cls")}


def test_every_tool_schema_matches_the_callable_it_invokes():
    problems = []
    for name, tool in tool_registry._tools.items():
        target = tool.target_callable()
        try:
            sig = inspect.signature(target)
        except (TypeError, ValueError):
            problems.append(f"{name}: no inspectable signature")
            continue
        params = _named_params(sig)
        fields = tool.input_model.model_fields
        if fields and not params:
            problems.append(f"{name}: invokes a **kwargs-only callable; use groundhog_forwarder()")
            continue
        for field in fields:
            if field not in params:
                problems.append(f"{name}: field '{field}' is not a parameter of {getattr(target, '__name__', target)}")
        for pname, p in params.items():
            if p.default is inspect.Parameter.empty and pname not in fields:
                problems.append(f"{name}: required parameter '{pname}' has no schema field")
        accepted = tool.input_model.geoai_accepted_keys()
        for key, field in accepted.items():
            if key in fields and key != field:
                problems.append(f"{name}: alias '{key}' of '{field}' shadows another field")
    assert not problems, "\n".join(problems)


# ---------------------------------------------------------------- results unchanged for correct inputs
@pytest.mark.parametrize("tool,args", [
    ("nq_frictionangle_sand", {"friction_angle": 32.0}),
    ("ngamma_frictionangle_vesic", {"friction_angle": 30.0}),
    ("k0_frictionangle_mesri", {"phi_cs": 30.0, "ocr": 2.0}),
    ("stresses_stripload", {"z": 3.0, "x": 0.5, "width": 2.0, "imposedstress": 150.0}),
    ("consolidationsettlement_mv", {"initial_height": 4.0, "effective_stress_increase": 80.0, "compressibility": 0.0003}),
    ("primaryconsolidationsettlement_nc", {"initial_height": 5.0, "initial_voidratio": 1.2, "initial_effective_stress": 60.0,
                                           "effective_stress_increase": 40.0, "compression_index": 0.4}),
    ("porosity_voidratio", {"voidratio": 0.7}),
    ("dryunitweight_watercontent", {"watercontent": 0.3, "bulkunitweight": 18.5}),
    ("relative_density", {"void_ratio": 0.6, "e_min": 0.4, "e_max": 0.9}),
    ("gmax_shearwavevelocity", {"Vs": 200.0, "gamma": 19.0}),
])
def test_registry_results_equal_direct_groundhog_calls(tool, args):
    direct = _groundhog(tool)(**args)
    output_model = tool_registry.get_tool(tool).output_model
    if output_model is not None:  # mirror GeoAITool.invoke: output model when it fits, else raw dict
        try:
            direct = output_model(**direct).model_dump()
        except Exception:
            pass
    _assert_same_result(_invoke(tool, **args), direct)
