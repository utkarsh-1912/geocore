def test_out_of_groundhog_range_is_a_clear_validation_error():
    # Groundhog's Andersen contours are calibrated for 1 <= su <= 100 kPa (it returns NaN outside).
    with pytest.raises(GeoAIValidationError, match="undrained_shear_strength"):
        tool_registry.invoke_tool("cycliccontours_dssclay_andersen",
                                  {"undrained_shear_strength": 200.0, "average_shear_stress": 10.0,
                                   "cyclic_shear_stress": 20.0})


def test_every_groundhog_function_is_exposed_or_excluded_with_reason():
    missing = [n for n in registry.function_map
               if n not in tool_registry._tools and n not in SKIPPED_FUNCTIONS and n not in MODEL_EXCLUDED_FUNCTIONS]
    assert not missing
    assert not SKIPPED_FUNCTIONS, SKIPPED_FUNCTIONS
    # Every function has an input schema (UI form validation), exposed to the model or not.
    assert all(n in SCHEMA_REGISTRY for n in registry.function_map)
    for name in ("stresses_lineload_retainingwall", "stresses_stripload_retainingwall", "piletest_chinkondler",
                 "pilegroupeffect_reesevanimpe", "reinforced_circularsection_inertia",
                 "bendingstiffness_soilmix_method1", "bendingstiffness_soilmix_method2"):
        assert tool_registry.get_tool(name) is not None, name


def test_previously_unregistered_function_matches_groundhog():
    args = dict(imposedstress=50.0, width=2.0, offset=1.0, toe_depth=5.0, depth=2.0)
    res = tool_registry.invoke_tool("stresses_stripload_retainingwall", args)
    res.pop("_provenance")
    direct = resolve_groundhog_object(registry.function_map["stresses_stripload_retainingwall"])(**args)
    assert res.keys() == direct.keys()
    for k, v in direct.items():
        if isinstance(v, float):
            assert res[k] == pytest.approx(v, rel=1e-12, nan_ok=True)
    model = tool_registry.get_tool("pilegroupeffect_reesevanimpe").input_model
    assert "List" in str(model.model_fields["pile_y"].annotation)


# ---------------------------------------------------------------- NaN defaults
_SPT = dict(N=20, borehole_diameter=100.0, rod_length=10.0, country="United States",
            hammertype="Safety", hammerrelease="Rope and pulley")


def test_nan_default_parameters_are_omitted_when_unset():
    fn = resolve_groundhog_object(registry.function_map["spt_N60_correction"])
    nan_params = [p for p, v in inspect.signature(fn).parameters.items()
                  if isinstance(v.default, float) and math.isnan(v.default)]
    assert nan_params == ["eta_H", "eta_B", "eta_S", "eta_R"]
    model = tool_registry.get_tool("spt_N60_correction").input_model
    assert model.geoai_omit_when_none == frozenset(nan_params)
    assert not set(nan_params) & set(model(**_SPT).geoai_call_kwargs())

    res = tool_registry.invoke_tool("spt_N60_correction", dict(_SPT))
    res.pop("_provenance")
    direct = fn(**_SPT)
    assert res == direct and res["N60 [-]"] == pytest.approx(20.0)
    # Forwarding None (the old behaviour) makes Groundhog return NaN for everything.
    assert math.isnan(fn(**_SPT, eta_H=None)["N60 [-]"])


def test_nan_default_parameter_still_accepts_explicit_value():
    fn = resolve_groundhog_object(registry.function_map["spt_N60_correction"])
    res = tool_registry.invoke_tool("spt_N60_correction", dict(_SPT, eta_H=55.0))
    res.pop("_provenance")
    assert res == fn(**_SPT, eta_H=55.0)
    res_null = tool_registry.invoke_tool("spt_N60_correction", dict(_SPT, eta_H="n/a"))
    res_null.pop("_provenance")
    assert res_null == fn(**_SPT)
