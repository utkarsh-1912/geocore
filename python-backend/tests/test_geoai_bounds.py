"""
Auto-schema bounds come from Groundhog's own validation (AGENTS.md §6, §7, §16).

- parameter_inventory.json bounds equal Groundhog's @Validator ranges wherever both exist
  (regenerate with ``python -m core.geoai.inventory_sync``);
- realistic engineering values validate (e.g. su in kPa is not capped at 1 kPa);
- every Groundhog function in the registry is exposed as a tool (or skipped with a reason);
- optional parameters whose Groundhog default is NaN are omitted from the call when unset.
"""
import inspect
import math

import pytest

from core.registry import registry
import core.geoai.tool_definitions  # noqa: F401
from core.geoai.exceptions import GeoAIValidationError
from core.geoai.inventory_sync import groundhog_validation_spec, resolve_groundhog_object
from core.geoai.schema_factory import MODEL_EXCLUDED_FUNCTIONS, SKIPPED_FUNCTIONS, _INVENTORY_BY_FUNC
from core.geoai.schemas import SCHEMA_REGISTRY
from core.geoai.tool_registry import tool_registry
from core.geoai.units import UnitDimension, get_unit_dimension


def _bound(v):
    return None if v == "" or v is None else float(v)


def _specs():
    for name, obj in registry.function_map.items():
        spec = groundhog_validation_spec(obj)
        if spec:
            yield name, obj, spec


def test_inventory_bounds_equal_groundhog_validation_ranges():
    drift = []
    for name, _, spec in _specs():
        for row in _INVENTORY_BY_FUNC.get(name, []):
            s = spec.get(row["parameter_name"])
            if not s or s.get("type") not in ("float", "int"):
                continue
            inv = (_bound(row["min_value"]), _bound(row["max_value"]))
            gh = (_bound(s.get("min_value")), _bound(s.get("max_value")))
            if inv != gh:
                drift.append(f"{name}.{row['parameter_name']}: inventory {inv} != Groundhog {gh}")
    assert not drift, "Run `python -m core.geoai.inventory_sync`:\n" + "\n".join(drift)


def test_schema_bounds_equal_groundhog_validation_ranges():
    drift = []
    for name, _, spec in _specs():
        tool = tool_registry.get_tool(name)
        if tool is None or not getattr(tool.input_model, "geoai_autogenerated", False):
            continue
        for field, fi in tool.input_model.model_fields.items():
            s = spec.get(field)
            if not s or s.get("type") not in ("float", "int"):
                continue
            ge = next((m.ge for m in fi.metadata if hasattr(m, "ge")), None)
            le = next((m.le for m in fi.metadata if hasattr(m, "le")), None)
            gh = (_bound(s.get("min_value")), _bound(s.get("max_value")))
            if (ge, le) != gh:
                drift.append(f"{name}.{field}: schema {(ge, le)} != Groundhog {gh}")
    assert not drift, "\n".join(drift)


# Upper bounds below these values would reject everyday engineering inputs.
_MIN_PLAUSIBLE_UPPER = {
    UnitDimension.PRESSURE: 10.0,       # kPa (Groundhog calibration ranges can be as low as 10 kPa)
    UnitDimension.UNIT_WEIGHT: 10.0,    # kN/m3 (submerged unit weights reach ~12)
    UnitDimension.ANGLE: 10.0,          # deg
    UnitDimension.LENGTH: 0.001,        # m (Hazen D10 is capped at 2 mm by Groundhog)
}


def _to_canonical(value, unit):
    from core.geoai.units import convert_unit
    base = {UnitDimension.PRESSURE: "kPa", UnitDimension.UNIT_WEIGHT: "kN/m3",
            UnitDimension.ANGLE: "deg", UnitDimension.LENGTH: "m"}
    return convert_unit(value, unit, base[get_unit_dimension(unit)])


def test_no_implausible_upper_bounds_on_auto_schemas():
    problems = []
    for name, tool in tool_registry._tools.items():
        if not getattr(tool.input_model, "geoai_autogenerated", False):
            continue
        for field, fi in tool.input_model.model_fields.items():
            unit = (fi.json_schema_extra or {}).get("unit", "-")
            dim = get_unit_dimension(unit) if unit != "-" else None
            le = next((m.le for m in fi.metadata if hasattr(m, "le")), None)
            if dim in _MIN_PLAUSIBLE_UPPER and le is not None and \
                    _to_canonical(le, unit) < _MIN_PLAUSIBLE_UPPER[dim]:
                problems.append(f"{name}.{field}: upper bound {le} {unit}")
    assert not problems, "\n".join(problems)


