"""
Calculation reports for checking: what was calculated, with what, how, and how far it can be trusted.

Built only from the stored run and from what the app already knows deterministically: the inputs (and, for values
taken from the project, their sources), the method and reference and the governing equation from the Groundhog
docstring (core/geoai/calculation_explainer.py), the results named through the quantity directory, the method's
verification status and benchmark relations, and whether the run is out of date. Nothing is generated by a model.
``render_html`` turns one or more reports into a self-contained printable HTML page.
"""
import datetime as _dt
import html
from typing import Any, Dict, List

from core.project.runs import get_run, list_runs


def build_report(run_id: int) -> Dict[str, Any]:
    from core.catalogue import find_method, load_benchmarks
    from core.catalogue.envelope import extract_values
    from core.geoai.calculation_explainer import explain_calculation
    run = get_run(run_id)
    if run is None:
        raise KeyError(run_id)
    fid = run["function_id"]
    hit = find_method(fid)
    results = run["results"]
    flat = results if isinstance(results, dict) and "results" not in results else {}
    exp = explain_calculation(fid, run["inputs"], flat)
    sources = {}
    for ri in run["inputs_from_project"]:
        sources.setdefault(ri["name"], ri["source"])
    return {
        "run": run_id,
        "title": hit["calculation"]["title"] if hit else fid,
        "method": hit["method"]["label"] if hit else fid,
        "function": fid,
        "created": _dt.datetime.fromtimestamp(run["created_at"]).strftime("%Y-%m-%d %H:%M"),
        "location": run.get("location"),
        "status": run.get("status") or "unverified",
        "status_note": (hit["method"].get("status_note") if hit else None),
        "benchmarks": [c["source"] for c in load_benchmarks().get(fid, [])],
        "standard": exp.get("standard"),
        "reference": exp.get("reference"),
        "formula": exp.get("formula"),
        "inputs": [{"name": i["label"] or i["key"], "key": i["key"], "value": i["value"], "unit": i["unit"],
                    "source": sources.get(i["key"], "entered by the user")} for i in exp["inputs"]],
        "results": [{"name": v["label"], "symbol": v["symbol"], "value": v["value"], "unit": v["unit"]}
                    for v in extract_values(fid, results)],
        "table": results.get("results") if isinstance(results, dict) and isinstance(results.get("results"), dict) else None,
        "stale": run["stale"],
        "review": run.get("review"),
        "note": run.get("note"),
    }


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.6g}"
    return html.escape(str(v)) if v is not None else "–"


def _review_html(r: Dict[str, Any]) -> str:
    e = html.escape
    rv = r.get("review")
    if not rv:
        return "<h3>Review</h3><p class=muted>Not reviewed.</p>"
    when = _dt.datetime.fromtimestamp(rv["reviewed_at"]).strftime("%Y-%m-%d %H:%M")
    out = f"<h3>Review</h3><p>Checked by <b>{e(rv['reviewer'])}</b> on {e(when)}.</p>"
    if rv.get("note"):
        out += f"<p>{e(rv['note'])}</p>"
    if r["stale"]:
        out += "<p class=stale>The run is out of date: this review applies to its earlier inputs. Re-run and review again.</p>"
    return out


def _one(r: Dict[str, Any]) -> str:
    e = html.escape
    rows_in = "".join(f"<tr><td>{e(str(i['name']))}</td><td class=n>{_fmt(i['value'])}</td><td>{e(i['unit'] or '')}</td>"
                      f"<td class=src>{e(i['source'])}</td></tr>" for i in r["inputs"])
    rows_out = "".join(f"<tr><td>{e(v['name'])}{' (' + e(v['symbol']) + ')' if v['symbol'] else ''}</td>"
                       f"<td class=n>{_fmt(v['value'])}</td><td>{e(v['unit'] or '')}</td></tr>" for v in r["results"])
    table = ""
    if r["table"] and isinstance(r["table"].get("data"), list) and r["table"]["data"]:
        data = r["table"]["data"]
        cols = r["table"].get("columns") or list(data[0])
        head = "".join(f"<th>{e(str(c))}</th>" for c in cols)
        body = "".join("<tr>" + "".join(f"<td class=n>{_fmt(row.get(c))}</td>" for c in cols) + "</tr>"
                       for row in data[:200])
        more = f"<p class=muted>{len(data) - 200} more rows not shown.</p>" if len(data) > 200 else ""
        table = f"<h3>Result table</h3><div class=wrap><table><tr>{head}</tr>{body}</table></div>{more}"
    status = {"verified": "Verified against closed-form cases", "corrected": "Corrected in GeoCore",
              "known_issue": "Known issue", "unverified": "Not yet verified in GeoCore"}.get(r["status"], r["status"])
    checks = "".join(f"<li>{e(b)}</li>" for b in r["benchmarks"])
    stale = ("<div class=stale><b>Out of date:</b><ul>" + "".join(f"<li>{e(s)}</li>" for s in r["stale"]) + "</ul></div>"
             if r["stale"] else "")
    return f"""<section>
<h2>{e(r['title'])} <span class=muted>· {e(r['method'])}</span></h2>
<p class=muted>Run #{r['run']} · {e(r['created'])}{' · ' + e(r['location']) if r['location'] else ''}</p>
{stale}
<h3>Method</h3>
<p>{e(r['standard'] or r['reference'] or 'Groundhog implementation')}{('<br>Reference: ' + e(r['reference'])) if r['reference'] and r['reference'] != r['standard'] else ''}</p>
<p><b>Status:</b> {e(status)}{('. ' + e(r['status_note'])) if r['status_note'] else ''}</p>
{('<p>Checked against:</p><ul>' + checks + '</ul>') if checks else ''}
{('<h3>Governing equation (LaTeX)</h3><pre>' + e(r['formula']) + '</pre>') if r['formula'] else ''}
<h3>Inputs</h3><table><tr><th>Input</th><th>Value</th><th>Unit</th><th>Source</th></tr>{rows_in}</table>
<h3>Results</h3><table><tr><th>Result</th><th>Value</th><th>Unit</th></tr>{rows_out or '<tr><td colspan=3>See the result table.</td></tr>'}</table>
{table}
{('<p><b>Note:</b> ' + e(r['note']) + '</p>') if r['note'] else ''}
{_review_html(r)}
</section>"""


def render_html(reports: List[Dict[str, Any]], title: str = "GeoCore calculation report") -> str:
    generated = _dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    body = "\n".join(_one(r) for r in reports) or "<p>No calculations have been saved to the project yet.</p>"
    return f"""<!doctype html><html lang=en><head><meta charset=utf-8><title>{html.escape(title)}</title>
<style>
body{{font:13px/1.45 system-ui,-apple-system,"Segoe UI",sans-serif;color:#13201a;max-width:960px;margin:24px auto;padding:0 16px}}
h1{{font-size:20px}} h2{{font-size:16px;margin:28px 0 2px;border-top:1px solid #d6e2d8;padding-top:14px}} h3{{font-size:13px;margin:14px 0 4px}}
table{{border-collapse:collapse;width:100%;margin:4px 0}} th,td{{border:1px solid #d6e2d8;padding:4px 6px;text-align:left;vertical-align:top}}
th{{background:#eef3ee}} td.n{{font-variant-numeric:tabular-nums;white-space:nowrap}} td.src{{color:#51605a;font-size:12px}}
.muted{{color:#51605a}} pre{{background:#f4f7f4;padding:8px;white-space:pre-wrap}} .wrap{{overflow-x:auto}}
.stale{{border:1px solid #c98a0b;background:#fbf3e2;padding:6px 10px;margin:8px 0}}
@media print{{section{{break-inside:avoid-page}}}}
</style></head><body>
<h1>{html.escape(title)}</h1>
<p class=muted>Generated {generated} by GeoCore. Calculations by Groundhog and GeoCore; check inputs, units and assumptions
against the project and the governing code. Engineering judgement remains with the user.</p>
{body}
</body></html>"""


def project_report_html() -> str:
    runs = list_runs()
    return render_html([build_report(r["id"]) for r in reversed(runs)], "GeoCore project calculations")
