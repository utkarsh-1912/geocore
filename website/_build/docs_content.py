"""
Docs pipeline for the GeoCore website: website/_content -> website/docs.

Input (generated by website/_content/extract_docs.py, treated as read-only):
  _content/nav.json              {home:{title,slug}, sections:[{title,slug,children?}]}
  _content/pages/<slug>.md       YAML front-matter + Markdown
  _content/groundhog/assets/**   figures, served at /docs/assets/groundhog/**

Output:
  docs/<slug>/index.html         one page per slug (URL /docs/<slug>/); slug "index" -> docs/index.html
  docs/assets/groundhog/**       mirrored figures
  docs/search-index.json         written by build.py from search_entries()

Math: $...$ and $$...$$ are stashed before Markdown and restored as \\(...\\) / \\[...\\] for the vendored
KaTeX auto-render (assets/js/math.js), so Markdown never touches LaTeX.

Author: Utkarsh Gupta
License: GPL v3
"""
from __future__ import annotations

import html
import json
import re
import shutil
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import markdown
import yaml

CONTENT_DIRNAME = "_content"
REQUIRED_FIELDS = ("title", "slug", "section", "description", "origin", "source_url", "license",
                   "author", "attribution", "groundhog_version", "edited_by_geocore")

# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------


def slug_url(slug: str) -> str:
    """Site-root-relative URL for a docs slug."""
    return "docs/" if slug == "index" else f"docs/{slug}/"


def groundhog_source_ref(content_dir: Path) -> str:
    """Git ref every upstream link must use: the commit (or tag) of the groundhog GeoCore ships,
    recorded by the extractor in groundhog/api.json."""
    api = json.loads((content_dir / "groundhog" / "api.json").read_text(encoding="utf-8"))
    return api.get("source_ref") or f"v{api['groundhog_version']}"


def load_nav(content_dir: Path) -> Tuple[Dict[str, Any], List[Dict[str, Any]]]:
    import json
    data = json.loads((content_dir / "nav.json").read_text(encoding="utf-8"))

    def convert(node: Dict[str, Any]) -> Dict[str, Any]:
        return {
            "title": node["title"],
            "slug": node["slug"].replace("/", "-"),
            "content_slug": node["slug"],
            "url": slug_url(node["slug"]),
            "children": [convert(c) for c in node.get("children", [])],
        }

    return data["home"], [convert(s) for s in data["sections"]]


def load_page(path: Path) -> Tuple[Dict[str, Any], str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        raise ValueError(f"{path}: missing front-matter")
    _, fm, body = text.split("---", 2)
    meta = yaml.safe_load(fm) or {}
    missing = [f for f in REQUIRED_FIELDS if f not in meta]
    if missing:
        raise ValueError(f"{path}: front-matter missing {missing}")
    return meta, body.lstrip("\n")


# ---------------------------------------------------------------------------
# Markdown with protected math
# ---------------------------------------------------------------------------

_FENCE_OPEN = re.compile(r"^[ ]{0,3}(?P<fence>`{3,}|~{3,})[ ]*[\w#.+-]*[ ]*(\{[^\n]*\})?[ ]*$")
_INLINE = re.compile(
    r"(?P<code>(?P<ticks>`+)(?:(?!(?P=ticks)).)+?(?P=ticks))"
    r"|\$\$(?P<disp>.+?)\$\$"
    r"|(?<![\\$])\$(?P<inl>[^$\n]+?)\$",
    re.S,
)


def _stash_math(body: str) -> Tuple[str, List[Tuple[str, str]]]:
    """Replace math with alphanumeric tokens outside fenced code and code spans."""
    stash: List[Tuple[str, str]] = []
    out: List[str] = []
    chunk: List[str] = []

    def flush() -> None:
        if not chunk:
            return
        text = "".join(chunk)
        chunk.clear()

        def repl(m: "re.Match[str]") -> str:
            if m.group("code"):
                return m.group(0)
            kind, tex = ("display", m.group("disp")) if m.group("disp") is not None else ("inline", m.group("inl"))
            stash.append((kind, tex.strip()))
            return f"GCMATH{len(stash) - 1}X"

        out.append(_INLINE.sub(repl, text))

    fence: Optional[str] = None
    for line in body.splitlines(keepends=True):
        stripped = line.rstrip("\n")
        if fence is None:
            m = _FENCE_OPEN.match(stripped)
            if m:
                flush()
                fence = m.group("fence")
                out.append(line)
            else:
                chunk.append(line)
        else:
            out.append(line)
            s = stripped.strip()
            if s and set(s) == {fence[0]} and len(s) >= len(fence):
                fence = None
    flush()
    return "".join(out), stash


def _sphinx_compat(kind: str, tex_src: str) -> str:
    """Sphinx wraps display math containing '&' or '\\\\' in a split environment; KaTeX needs it explicit."""
    if kind == "display" and ("&" in tex_src or "\\\\" in tex_src) and "\\begin{" not in tex_src:
        return "\\begin{aligned}" + tex_src + "\\end{aligned}"
    return tex_src


def _restore_math(html_text: str, stash: List[Tuple[str, str]]) -> str:
    def tex(i: int) -> str:
        return html.escape(_sphinx_compat(*stash[i]), quote=False)

    def block(m: "re.Match[str]") -> str:
        i = int(m.group(1))
        if stash[i][0] == "display":
            return f'<div class="math-display">\\[{tex(i)}\\]</div>'
        return m.group(0)

    html_text = re.sub(r"<p>\s*GCMATH(\d+)X\s*</p>", block, html_text)

    def inline(m: "re.Match[str]") -> str:
        i = int(m.group(1))
        if stash[i][0] == "display":
            return f'<span class="math-display-inline">\\[{tex(i)}\\]</span>'
        return f'<span class="math">\\({tex(i)}\\)</span>'

    return re.sub(r"GCMATH(\d+)X", inline, html_text)


def _plain_math(text: str, stash: List[Tuple[str, str]]) -> str:
    return re.sub(r"GCMATH(\d+)X", lambda m: stash[int(m.group(1))][1], text)


def make_markdown() -> markdown.Markdown:
    return markdown.Markdown(
        extensions=["tables", "fenced_code", "codehilite", "toc", "attr_list", "md_in_html", "sane_lists"],
        extension_configs={
            "codehilite": {"css_class": "highlight", "guess_lang": False, "use_pygments": True},
            "toc": {"permalink": False, "toc_depth": "2-3"},
        },
        output_format="html",
    )


def render_markdown(md: markdown.Markdown, body: str) -> Tuple[str, List[Dict[str, Any]], bool]:
    """Return (html, toc tokens flattened, has_math)."""
    md.reset()
    text, stash = _stash_math(body)
    out = md.convert(text)
    out = _restore_math(out, stash)
    toc: List[Dict[str, Any]] = []

    def walk(tokens: List[Dict[str, Any]]) -> None:
        for t in tokens:
            name = html.unescape(re.sub(r"<[^>]+>", "", t.get("name", "")))
            toc.append({"id": t["id"], "title": _plain_math(name, stash), "level": t["level"]})
            walk(t.get("children", []))

    walk(getattr(md, "toc_tokens", []))
    # Prefer the explicit <a id="..."></a> anchors that precede API headings (stable, documented ids).
    explicit = dict((h, a) for a, h in re.findall(r'<a id="([^"]+)"></a>\s*(?:</p>)?\s*<h[23] id="([^"]+)"', out))
    for t in toc:
        t["id"] = explicit.get(t["id"], t["id"])
    return out, toc, bool(stash)


# ---------------------------------------------------------------------------
# Link rewriting and checks
# ---------------------------------------------------------------------------

_DOCS_LINK = re.compile(r'(href|src)="/docs/([^"#?]*)([#?][^"]*)?"')


def rewrite_links(page_html: str, known_slugs: set, asset_root: Path, problems: List[str], where: str) -> str:
    """/docs/<slug> -> /docs/<slug>/ (pretty URL); verify slugs and image files exist."""
    def repl(m: "re.Match[str]") -> str:
        attr, path, tail = m.group(1), m.group(2), m.group(3) or ""
        if path.startswith("assets/groundhog/"):
            if not (asset_root / path[len("assets/groundhog/"):]).is_file():
                problems.append(f"{where}: missing image /docs/{path}")
            return f'{attr}="/docs/{path}{tail}"'
        slug = path.rstrip("/") or "index"
        if slug not in known_slugs:
            problems.append(f"{where}: link to unknown page /docs/{path}")
            return m.group(0)
        return f'{attr}="/{slug_url(slug)}{tail}"'

    return _DOCS_LINK.sub(repl, page_html)


_EXT_IMG = re.compile(r'<img\b[^>]*\bsrc="(https?://[^"]+)"[^>]*>')


def _external_image(m: "re.Match[str]") -> str:
    """Third-party images (e.g. PyPI/Binder badges) would break the CSP and leak visits; show their alt text."""
    alt = re.search(r'\balt="([^"]*)"', m.group(0))
    label = (alt.group(1) if alt else "") or "external image"
    return f'<span class="ext-img" title="{html.escape(m.group(1))}">{label}</span>'


def decorate_html(page_html: str) -> str:
    """Replace external images, wrap tables for horizontal scrolling and make images lazy."""
    page_html = _EXT_IMG.sub(_external_image, page_html)
    page_html = re.sub(r"<table>", '<div class="table-wrap"><table class="data">', page_html)
    page_html = page_html.replace("</table>", "</table></div>")
    page_html = re.sub(r"<img (?![^>]*loading=)", '<img loading="lazy" decoding="async" ', page_html)
    return page_html


def plain_text(page_html: str) -> str:
    text = re.sub(r"<(pre|script|style)\b.*?</\1>", " ", page_html, flags=re.S)
    text = re.sub(r"<[^>]+>", " ", text)
    text = html.unescape(text)
    text = re.sub(r"\\[()\[\]]", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def inline_title(title: str) -> Tuple[str, str]:
    """Front-matter titles may contain Markdown code spans (```groundhog```). Return (text, html)."""
    text = re.sub(r"`+([^`]+?)`+", r"\1", title)
    parts = re.split(r"`+([^`]+?)`+", title)
    out = []
    for i, p in enumerate(parts):
        out.append(f"<code>{html.escape(p)}</code>" if i % 2 else html.escape(p))
    return text, "".join(out)


