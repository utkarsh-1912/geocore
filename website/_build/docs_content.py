def mirror_assets(src: Path, dst: Path) -> Tuple[int, int]:
    """Copy src tree to dst, skipping unchanged files and removing stale ones. Returns (files, bytes)."""
    count = size = 0
    seen = set()
    if src.is_dir():
        for f in src.rglob("*"):
            if not f.is_file():
                continue
            rel = f.relative_to(src)
            target = dst / rel
            seen.add(target)
            st = f.stat()
            count += 1
            size += st.st_size
            if target.exists() and target.stat().st_size == st.st_size and target.stat().st_mtime >= st.st_mtime:
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, target)
    if dst.is_dir():
        for f in sorted(dst.rglob("*"), reverse=True):
            if f.is_file() and f not in seen:
                f.unlink()
            elif f.is_dir() and not any(f.iterdir()):
                f.rmdir()
    return count, size


