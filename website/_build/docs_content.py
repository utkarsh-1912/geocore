def build_pages(content_dir: Path, website: Path, problems: List[str]) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]], Dict[str, Any]]:
    """Return (docs_nav, pages, home_page). Pages are dicts following the docs page contract."""
    home, nav = load_nav(content_dir)
    source_ref = groundhog_source_ref(content_dir)
    pages_dir = content_dir / "pages"
    asset_src = content_dir / "groundhog" / "assets"
    known = {p.relative_to(pages_dir).with_suffix("").as_posix() for p in pages_dir.rglob("*.md")}

    nav_slugs = {home["slug"]}

    def collect(nodes: List[Dict[str, Any]]) -> None:
        for n in nodes:
            nav_slugs.add(n["content_slug"])
            collect(n["children"])
    collect(nav)
    for s in sorted(known - nav_slugs):
        problems.append(f"page not in nav: {s}")
    for s in sorted(nav_slugs - known):
        problems.append(f"nav entry without page: {s}")

    md = make_markdown()
    pages: List[Dict[str, Any]] = []
    home_page: Dict[str, Any] = {}
    for slug in sorted(known):
        meta, body = load_page(pages_dir / f"{slug}.md")
        if meta["slug"] != slug:
            problems.append(f"{slug}: front-matter slug is {meta['slug']!r}")
        body_html, toc, has_math = render_markdown(md, body)
        body_html = rewrite_links(body_html, known, asset_src, problems, slug)
        body_html = decorate_html(body_html)
        title_text, title_html = inline_title(str(meta["title"]))
        if meta.get("origin") == "groundhog" and f"/{source_ref}/" not in str(meta.get("source_url", "")) \
                and "/tree/" not in str(meta.get("source_url", "")):
            problems.append(f"{slug}: source_url not pinned to {source_ref}")
        toc_full = toc
        # Long API pages: keep the right-hand TOC readable (h2 only when there are many entries).
        if len(toc) > 40:
            toc = [t for t in toc if t["level"] == 2]
        upstream = meta.get("upstream_docs_urls") or ([meta["upstream_docs_url"]] if meta.get("upstream_docs_url") else [])
        page = {
            "slug": slug,
            "title": title_text,
            "title_html": title_html,
            "description": meta.get("description"),
            "url": slug_url(slug),
            "body_html": body_html,
            "toc": toc,
            "toc_full": toc_full,
            "has_math": has_math,
            "meta": {
                "section": meta.get("section"),
                "origin": meta.get("origin"),
                "author": meta.get("author"),
                "license": meta.get("license"),
                "attribution": meta.get("attribution"),
                "source_url": meta.get("source_url"),
                "groundhog_version": meta.get("groundhog_version"),
                "edited_by_geocore": bool(meta.get("edited_by_geocore")),
                "edit_note": meta.get("geocore_edit_note"),
                "upstream_docs_urls": upstream,
                "module": meta.get("module"),
                "geocore_available": meta.get("geocore_available"),
                "geocore_functions": meta.get("geocore_functions") or [],
                "notebook": meta.get("notebook"),
                "sources": meta.get("sources") or [],
            },
            "plain": plain_text(body_html),
        }
        if slug == home["slug"]:
            home_page = page
        else:
            pages.append(page)

    count, size = mirror_assets(asset_src, website / "docs" / "assets" / "groundhog")
    home_page.setdefault("stats", {})
    home_page["stats"] = {"images": count, "image_bytes": size}
    return nav, pages, home_page


def search_entries(pages: List[Dict[str, Any]], body_chars: int = 600) -> List[Dict[str, Any]]:
    """One entry per page, plus one per h2/h3 anchor on API reference pages (function/class names)."""
    entries: List[Dict[str, Any]] = []
    for p in pages:
        summary = p["description"] or ""
        entries.append({
            "id": "doc-" + p["slug"].replace("/", "-"),
            "title": p["title"],
            "url": p["url"],
            "section": p["meta"]["section"] or "Docs",
            "summary": summary,
            "headings": [t["title"] for t in p["toc"]][:30],
            "body": p["plain"][:body_chars],
        })
        if p["meta"].get("module"):
            for t in p["toc_full"]:
                name = t["title"].replace("class ", "").strip()
                entries.append({
                    "id": f"api-{p['slug'].replace('/', '-')}-{t['id']}",
                    "title": name,
                    "url": f"{p['url']}#{t['id']}",
                    "section": p["meta"]["module"],
                    "summary": "",
                    "headings": [],
                    "body": "",
                })
    return entries
